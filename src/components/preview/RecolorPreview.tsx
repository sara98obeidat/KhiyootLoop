"use client";

import { useEffect, useRef, useState } from "react";
import { BASE_IMAGES, RECOLOR_LABEL, findBaseImage, getBaseImageById, type BaseImage } from "@/config/baseImages";
import { PRODUCTS, TAG_MATERIALS, findOption } from "@/config/catalog";
import { paletteEntry } from "@/config/palette";
import type { ProductConfiguration } from "@/lib/configuration";
import { prepareBase, recolor, type PreparedBase } from "@/lib/recolor";
import { DimensionDiagram } from "./DimensionDiagram";
import { TagCloseUp, TagDefs, TagGraphic } from "./TagLayer";

/**
 * Recoloured preview (version "recolor-preview-v1"):
 *  1. the light-cream base photo for the chosen product + stitch + material,
 *  2. the fabric (and only the fabric, via its mask) recoloured in the browser,
 *  3. the leather or metal tag and the customer's exact text as SVG layers.
 * Nothing is generated by an external service; size is shown by the
 * dimensions and the diagram, never by enlarging the photo.
 */

interface Loaded {
  prep: PreparedBase;
  pixels: Uint8ClampedArray;
}

const prepared = new Map<string, Promise<Loaded>>();
const rendered = new Map<string, ImageData>();
const RENDER_CACHE_SIZE = 8;

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.decoding = "async";
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error(`Could not load ${src}`));
    img.src = src;
  });
}

function pixelsOf(img: HTMLImageElement, w: number, h: number): Uint8ClampedArray {
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const ctx = c.getContext("2d", { willReadFrequently: true });
  if (!ctx) throw new Error("Canvas is not available");
  ctx.drawImage(img, 0, 0, w, h);
  return ctx.getImageData(0, 0, w, h).data;
}

function loadBase(base: BaseImage): Promise<Loaded> {
  let p = prepared.get(base.id);
  if (!p) {
    p = Promise.all([loadImage(base.src), loadImage(base.maskSrc)]).then(([img, mask]) => {
      const pixels = pixelsOf(img, base.width, base.height);
      const maskPixels = pixelsOf(mask, base.width, base.height);
      return { prep: prepareBase(pixels, maskPixels, base.width, base.height), pixels };
    });
    p.catch(() => prepared.delete(base.id));
    prepared.set(base.id, p);
  }
  return p;
}

async function renderColour(base: BaseImage, hex: string, texture: number): Promise<ImageData> {
  const key = `${base.id}|${hex}|${texture}`;
  const hit = rendered.get(key);
  if (hit) return hit;
  const { prep, pixels } = await loadBase(base);
  const data = new ImageData(recolor(prep, pixels, hex, texture), base.width, base.height);
  rendered.set(key, data);
  if (rendered.size > RENDER_CACHE_SIZE) rendered.delete(rendered.keys().next().value!);
  return data;
}

/** Warm up the other base photos of the same product when the browser is idle. */
function prefetchSiblings(base: BaseImage) {
  const idle = (cb: () => void) => {
    if (typeof window.requestIdleCallback === "function") window.requestIdleCallback(cb, { timeout: 3000 });
    else setTimeout(cb, 800);
  };
  for (const b of BASE_IMAGES) {
    if (b.product === base.product && b.id !== base.id && !prepared.has(b.id)) idle(() => void loadBase(b).catch(() => {}));
  }
}

type Status = "loading" | "ready" | "error";

export function RecolorPreview({
  config,
  baseId,
  idPrefix = "rp",
  compact = false,
}: {
  config: ProductConfiguration;
  /** For saved orders: the base image id stored with the order. */
  baseId?: string | null;
  idPrefix?: string;
  compact?: boolean;
}) {
  const product = PRODUCTS[config.product];
  const base = baseId === undefined ? findBaseImage(config) : getBaseImageById(baseId);
  const colour = paletteEntry(config.color);
  const stitch = findOption(product.stitches, config.stitch);
  const material = findOption(product.materials, config.material);
  const tag = findOption(TAG_MATERIALS, config.tagMaterial);
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const [state, setState] = useState<{ key: string; status: Status }>({ key: "", status: "loading" });
  const useBasePhoto = Boolean(colour?.useBasePhoto);
  const key = base && colour ? `${base.id}|${colour.hex}|${colour.texture}` : "";

  useEffect(() => {
    if (!base || !colour || useBasePhoto) return;
    let cancelled = false;
    renderColour(base, colour.hex, colour.texture)
      .then((data) => {
        if (cancelled) return;
        const c = canvasRef.current;
        const ctx = c?.getContext("2d");
        if (!c || !ctx) throw new Error("Canvas is not available");
        ctx.putImageData(data, 0, 0);
        setState({ key, status: "ready" });
        prefetchSiblings(base);
      })
      .catch(() => !cancelled && setState({ key, status: "error" }));
    return () => {
      cancelled = true;
    };
  }, [base, colour, useBasePhoto, key]);

  useEffect(() => {
    if (base && useBasePhoto) prefetchSiblings(base);
  }, [base, useBasePhoto]);

  const status: Status = useBasePhoto ? "ready" : state.key === key ? state.status : "loading";
  const tagText = config.tagText || "Your text";
  const description = `${colour?.label ?? config.color} ${product.name.toLowerCase()}, ${stitch?.label.toLowerCase() ?? ""}, ${
    material?.label ?? ""
  }, with a ${tag?.label.toLowerCase() ?? "tag"} reading: ${config.tagText || "(no text yet)"}. AI-generated concept preview.`;

  return (
    <div className="concept-preview" data-base-id={base?.id ?? "none"} data-status={status}>
      {base && colour ? (
        <div
          className="concept-frame"
          style={{ aspectRatio: `${base.width} / ${base.height}` }}
          role="img"
          aria-label={description}
        >
          {useBasePhoto ? (
            // eslint-disable-next-line @next/next/no-img-element
            <img src={base.src} width={base.width} height={base.height} alt="" />
          ) : (
            <>
              {status !== "ready" && (
                // Shown faded and blurred only while the colour is being applied.
                // eslint-disable-next-line @next/next/no-img-element
                <img src={base.src} width={base.width} height={base.height} alt="" className="recolor-pending" />
              )}
              <canvas
                ref={canvasRef}
                width={base.width}
                height={base.height}
                className="recolor-canvas"
                style={{ visibility: status === "ready" ? "visible" : "hidden" }}
              />
              {status === "loading" && <p className="recolor-status">Applying {colour.label.toLowerCase()}…</p>}
              {status === "error" && (
                <p className="recolor-status">
                  The colour preview could not be drawn in this browser. Selected colour: {colour.label}.
                </p>
              )}
            </>
          )}
          <svg className="concept-overlay" viewBox={`0 0 ${base.width} ${base.height}`} aria-hidden="true" focusable="false">
            <TagDefs prefix={idPrefix} />
            <TagGraphic prefix={idPrefix} box={base.tag} material={config.tagMaterial} text={tagText} pad={2} />
          </svg>
          <p className="concept-label">{RECOLOR_LABEL}</p>
        </div>
      ) : (
        <div className="concept-missing" role="status" data-testid="concept-missing">
          <span className="concept-swatch" style={{ background: colour?.hex ?? "#ccc" }} aria-hidden="true" />
          <p>
            <strong>No base image yet for this stitch and material.</strong>
            <br />
            {product.name}: {stitch?.label} · {material?.label} · {colour?.label}.
          </p>
          <p className="small muted">Your order still records exactly these options.</p>
        </div>
      )}

      {!compact && (
        <>
          <div className="concept-tag-closeup">
            <p className="small muted">Your tag, enlarged{config.tagText ? "" : " (example text)"}</p>
            <TagCloseUp
              prefix={`${idPrefix}-cu`}
              material={config.tagMaterial}
              text={tagText}
              label={`${tag?.label ?? "Tag"} reading: ${config.tagText || "(no text yet)"}`}
            />
          </div>
          <DimensionDiagram product={config.product} size={config.size} />
        </>
      )}
    </div>
  );
}
